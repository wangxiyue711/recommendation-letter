function buildPrompt(facts) {
  const factText = facts
    .map((fact) => `- ${fact.label}: ${fact.value}`)
    .join("\n");

  return `あなたは日本の人材紹介会社で推薦文を作成するキャリアアドバイザーです。
候補者情報だけを根拠に、企業へ送付する日本語の推薦文本文を作成してください。

出力条件:
- 推薦文本文のみを出力する。件名、宛名、見出し、箇条書き、注釈は不要。
- 500〜700字程度、4段落構成。
- 入力されていない事実は絶対に作らない。会社名、職種、年数、資格、成果、実績、性格、志望理由、面談所感を推測で補わない。
- 応募ポジションや希望職種を、実務経験として誤って書かない。
- 欠点を説明する段落は作らない。「一方で」「懸念材料」「不安要素」「実績が限られている」「経験が浅い」は使わない。
- 未経験や早期転職などが入力されている場合は、短く前提として触れ、すぐに入力済みの経験・姿勢・学習意欲・人柄に接続する。

必ずこの4層で書く:
1. 紹介: 候補者の全体像を紹介する。「〇〇様は、〜の方です。」または「〇〇様は、これまで〜に従事されてこられました。」に近い自然な入り方にする。
2. 経験から強みへ: 職務経験、担当業務、研修、学習、顧客対応などの具体例を使い、そこから読み取れる強みを導く。
3. 応募職種での価値: その経験と強みが、現在応募したい職種・ポジションでどのような優位性につながるかを説明する。根拠以上の成果予測はしない。
4. 推薦と面接依頼: 推薦者として一度会う価値がある理由をまとめ、「ぜひ一度、面接にて〜をご判断いただけますと幸いです。」に近い形で締める。

文体:
- 参考例文のように、丁寧で自然な人材紹介の推薦文にする。
- 強みは抽象語だけで終わらせず、入力された経験や行動と結びつける。
- 断定しすぎず、「考えております」「見受けられます」「うかがえます」「推察しております」を自然に使う。
- 参考例文の事実や文章をコピーせず、文体と段落展開だけを参考にする。

参考例文:
${styleReferenceExamples}

候補者情報:
${factText}`;
}

async function generateRecommendation(facts) {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    throw new Error("missing_api_key");
  }

  const model = process.env.OPENAI_MODEL || "gpt-4o-mini";

  const response = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${apiKey}`,
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      model,
      temperature: 0.45,
      messages: [
        {
          role: "system",
          content: "You write factual, nuanced, professional Japanese recruiter recommendation letters. Never invent facts. Output only the final Japanese letter body."
        },
        {
          role: "user",
          content: buildPrompt(facts)
        }
      ]
    })
  });

  if (!response.ok) {
    const detail = await response.text();
    throw new Error(`openai_error:${response.status}:${detail.slice(0, 300)}`);
  }

  const data = await response.json();
  const text = data.choices?.[0]?.message?.content?.trim();

  if (!text) {
    throw new Error("empty_response");
  }

  return text;
}

export default async function handler(req, res) {
  // CORS headers
  res.setHeader("Access-Control-Allow-Credentials", "true");
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "GET,OPTIONS,PATCH,DELETE,POST,PUT");
  res.setHeader(
    "Access-Control-Allow-Headers",
    "X-CSRF-Token, X-Requested-With, Accept, Accept-Version, Content-Length, Content-MD5, Content-Type, Date, X-Api-Version"
  );

  if (req.method === "OPTIONS") {
    res.status(200).end();
    return;
  }

  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed" });
  }

  try {
    const { facts } = req.body || {};

    if (!Array.isArray(facts)) {
      return res.status(400).json({ error: "候補者に関する情報を少なくとも1つ入力してください。" });
    }

    const validFacts = facts
      .filter((fact) => typeof fact?.label === "string" && typeof fact?.value === "string")
      .map((fact) => ({ label: fact.label.trim(), value: fact.value.trim() }))
      .filter((fact) => fact.label && fact.value);

    if (validFacts.length === 0) {
      return res.status(400).json({ error: "候補者に関する情報を少なくとも1つ入力してください。" });
    }

    const recommendation = await generateRecommendation(validFacts);
    return res.status(200).json({ recommendation });
  } catch (error) {
    if (error.message === "missing_api_key") {
      return res.status(500).json({ error: "OPENAI_API_KEY が設定されていません。" });
    }

    return res.status(500).json({
      error: "推薦文の生成中にエラーが発生しました。",
      detail: error.message
    });
  }
}
